#!/usr/bin/env python3
"""Generate fnirsi-dso-tc3/cal.h from host/scope_cal.json (volts correction per V/div index).

usage: sigrok/gen_cal.py            # rewrites sigrok/fnirsi-dso-tc3/cal.h
"""
import json, os

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "..", "host", "scope_cal.json")))
out = ["/* Generated by sigrok/gen_cal.py from host/scope_cal.json. Do not edit.",
       " * true = (scope - b) / k; k == 0 means no correction for that index. */", ""]
for probe, name in ((0, "x1"), (1, "x10")):
    rng = d.get(name, {}).get("ranges", {})
    rows = []
    for i in range(10):
        r = rng.get(str(i))
        rows.append("\t{ %.6f, %.6f }," % (r["k"], r["b"]) if r else "\t{ 0.0, 0.0 },")
    out += ["static const struct { double k, b; } tc3_cal_%s[10] = {" % name] + rows + ["};", ""]
open(os.path.join(here, "fnirsi-dso-tc3", "cal.h"), "w").write("\n".join(out))
print("wrote cal.h")
